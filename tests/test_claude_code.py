"""Claude Code source: the x2.3 overcount, the row counter and the prompt filter."""
from __future__ import annotations

import json

from fuentes import claude_code


def linea(mid, bloque, usage, ts="2026-09-10T10:00:00.000Z", **extra):
    return json.dumps({
        "type": "assistant", "sessionId": "s1", "cwd": "/home/demo/projects/webshop",
        "timestamp": ts, "uuid": f"u-{mid}-{bloque}",
        "message": {"id": mid, "role": "assistant", "model": "claude-opus-5",
                    "content": [{"type": "text", "text": bloque}], "usage": usage},
        **extra,
    })


def escribir(casa, *lineas, nombre="s1.jsonl"):
    ruta = casa / ".claude" / "projects" / "-home-demo-projects-webshop" / nombre
    ruta.parent.mkdir(parents=True, exist_ok=True)
    with ruta.open("a") as f:
        for x in lineas:
            f.write(x + "\n")
    return ruta


def test_same_message_split_in_blocks_counts_once(cx, casa):
    u1 = {"input_tokens": 10, "output_tokens": 500, "cache_read_input_tokens": 1000}
    u2 = {"input_tokens": 5, "output_tokens": 50}
    # 4 lines with usage, but only 2 distinct messages: 3 blocks of msg_A share its usage.
    escribir(casa, linea("msg_A", "a1", u1), linea("msg_A", "a2", u1), linea("msg_A", "a3", u1),
             linea("msg_B", "b1", u2, ts="2026-09-10T10:01:00.000Z"))

    nuevas = claude_code.leer(cx)

    assert cx.execute("SELECT COUNT(*) FROM uso").fetchone()[0] == 2
    assert nuevas == 2, "the counter must report NEW rows, not processed lines"
    salida = cx.execute("SELECT SUM(t_salida) FROM uso").fetchone()[0]
    assert salida == 550                          # summing every line would give 1550


def test_second_pass_is_idempotent(cx, casa):
    u = {"input_tokens": 1, "output_tokens": 2}
    ruta = escribir(casa, linea("msg_A", "a1", u))
    assert claude_code.leer(cx) == 1
    # Force a full re-read of the same bytes: UNIQUE(ref) must absorb it.
    cx.execute("DELETE FROM lectura")
    assert claude_code.leer(cx) == 0
    assert cx.execute("SELECT COUNT(*) FROM uso").fetchone()[0] == 1
    assert ruta.exists()


def test_subagent_transcripts_are_read(cx, casa):
    u = {"input_tokens": 1, "output_tokens": 2}
    escribir(casa, linea("msg_S", "s", u, isSidechain=True), nombre="s1/subagents/agent-1.jsonl")
    claude_code.leer(cx)
    fila = cx.execute("SELECT proyecto FROM uso").fetchone()
    assert fila[0] == "webshop"                   # attributed to the project, not to the subfolder


def test_prompt_filter_drops_injected_user_lines():
    assert claude_code._es_tuyo("Añade validación al formulario")
    assert not claude_code._es_tuyo("<command-name>/clear</command-name>")
    assert not claude_code._es_tuyo("[image: captura.png]")
    assert not claude_code._es_tuyo("Caveat: the messages below were generated by the user")
    assert not claude_code._es_tuyo("ok")


def test_missing_folder_is_an_error_with_a_short_path(cx, casa):
    claude_code.leer(cx)
    error = cx.execute("SELECT error FROM salud WHERE fuente='claude_code'").fetchone()[0]
    assert error.startswith("No existe ~/")
