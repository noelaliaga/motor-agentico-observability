"""Claude Code source: the x2.3 overcount, the row counter and the prompt filter."""
from __future__ import annotations

import json

from sources import claude_code


def line(mid, block, usage, ts="2026-09-10T10:00:00.000Z", **extra):
    return json.dumps({
        "type": "assistant", "sessionId": "s1", "cwd": "/home/demo/projects/webshop",
        "timestamp": ts, "uuid": f"u-{mid}-{block}",
        "message": {"id": mid, "role": "assistant", "model": "claude-opus-5",
                    "content": [{"type": "text", "text": block}], "usage": usage},
        **extra,
    })


def write(home, *lines, name="s1.jsonl"):
    path = home / ".claude" / "projects" / "-home-demo-projects-webshop" / name
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a") as f:
        for x in lines:
            f.write(x + "\n")
    return path


def test_same_message_split_in_blocks_counts_once(cx, home):
    u1 = {"input_tokens": 10, "output_tokens": 500, "cache_read_input_tokens": 1000}
    u2 = {"input_tokens": 5, "output_tokens": 50}
    # 4 lines with usage, but only 2 distinct messages: 3 blocks of msg_A share its usage.
    write(home, line("msg_A", "a1", u1), line("msg_A", "a2", u1), line("msg_A", "a3", u1),
          line("msg_B", "b1", u2, ts="2026-09-10T10:01:00.000Z"))

    new = claude_code.read(cx)

    assert cx.execute("SELECT COUNT(*) FROM usage").fetchone()[0] == 2
    assert new == 2, "the counter must report NEW rows, not processed lines"
    output = cx.execute("SELECT SUM(t_output) FROM usage").fetchone()[0]
    assert output == 550                          # summing every line would give 1550


def test_second_pass_is_idempotent(cx, home):
    u = {"input_tokens": 1, "output_tokens": 2}
    path = write(home, line("msg_A", "a1", u))
    assert claude_code.read(cx) == 1
    # Force a full re-read of the same bytes: UNIQUE(ref) must absorb it.
    cx.execute("DELETE FROM read_cursors")
    assert claude_code.read(cx) == 0
    assert cx.execute("SELECT COUNT(*) FROM usage").fetchone()[0] == 1
    assert path.exists()


def test_subagent_transcripts_are_read(cx, home):
    u = {"input_tokens": 1, "output_tokens": 2}
    write(home, line("msg_S", "s", u, isSidechain=True), name="s1/subagents/agent-1.jsonl")
    claude_code.read(cx)
    row = cx.execute("SELECT project FROM usage").fetchone()
    assert row[0] == "webshop"                    # attributed to the project, not to the subfolder


def test_prompt_filter_drops_injected_user_lines():
    assert claude_code._is_yours("Add validation to the form")
    assert not claude_code._is_yours("<command-name>/clear</command-name>")
    assert not claude_code._is_yours("[image: screenshot.png]")
    assert not claude_code._is_yours("Caveat: the messages below were generated by the user")
    assert not claude_code._is_yours("ok")


def test_missing_folder_is_an_error_with_a_short_path(cx, home):
    claude_code.read(cx)
    error = cx.execute("SELECT error FROM health WHERE source='claude_code'").fetchone()[0]
    assert error.startswith("~/") and error.endswith(" does not exist")
